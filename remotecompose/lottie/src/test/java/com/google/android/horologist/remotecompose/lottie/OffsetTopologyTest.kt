/** Reference geometry is generated by pinned Lottie-web, not by the Kotlin offset modifier. */
class OffsetTopologyTest : MotionPixelHarness() {
  @Test
  fun orderedReferenceRetainsOriginalStarFrame() {
    val root =
      Json.parseToJsonElement(
          checkNotNull(javaClass.getResource("/offset-topology-reference.json")).readText()
        )
        .jsonObject
    assertThat(root.getValue("intersectionOrder").jsonPrimitive.content).isEqualTo("ascending-t")
    assertThat(root.getValue("originalOrderRetained").jsonPrimitive.content)
      .isEqualTo("webExpected")
    val cases = root.getValue("cases").jsonArray.map { it.jsonObject }
    for (case in cases) for (frame in case.getValue("frames").jsonArray) {
      assertThat(frame.jsonObject.containsKey("webExpected")).isTrue()
    }
    val frame =
      cases
        .single { it.getValue("name").jsonPrimitive.content == "rounded-star" }
        .getValue("frames")
        .jsonArray[6]
        .jsonObject
    assertThat(frame.getValue("expected")).isNotEqualTo(frame.getValue("webExpected"))
  }

