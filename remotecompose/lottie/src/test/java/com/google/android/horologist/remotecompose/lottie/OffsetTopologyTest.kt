  private fun verifySplitAmount(kind: String, padded: Boolean) {
    val fixture =
      Json.parseToJsonElement(
          checkNotNull(javaClass.getResource("/offset-topology-reference.json")).readText()
        )
        .jsonObject
        .getValue("cases")
        .jsonArray
        .map { it.jsonObject }
        .single { it.getValue("name").jsonPrimitive.content == "split-prune-$kind" }
    val source = fixture.getValue("input").jsonArray.single().toString()
    val rounding = if (padded) """,{"ty":"rd","r":${fixed("1")}}""" else ""
    val offset = """{"ty":"op","a":${fixture.getValue("amount")},"lj":1,"ml":${fixed("100")}}"""
    val stroke =
      """{"ty":"st","c":${fixed("[1,0,0,1]")},"o":${fixed("100")},"w":${fixed("2")},"lc":1,"lj":1,"ml":100}"""
    assertMatchesStaticFrames(
      animation("$source$rounding,$offset,$stroke"),
      referenceProbeAt = { Probe(32, 32, 1f, 1f) },
      artifactName = "offset-topology-split-prune-$kind${if (padded) "-padded" else ""}",
      frames = (0..10).toList() + listOf(5, 0, 10, 0, 5),
      maxMeanRedError = .0002f,
      maxPeakRedError = .3f,
      staticAt = { frame ->
        val path = fixture.getValue("frames").jsonArray[frame].jsonObject.getValue("expected")
        animation("""{"ty":"sh","ks":${fixed(path.toString())}},$stroke""")
      },
    )
  }

  private fun verifySplitPrune(dynamic: Boolean, padded: Boolean) {
    val fixture =
      Json.parseToJsonElement(
          checkNotNull(javaClass.getResource("/offset-topology-reference.json")).readText()
        )
        .jsonObject
        .getValue("cases")
        .jsonArray
        .map { it.jsonObject }
        .single { it.getValue("name").jsonPrimitive.content == "split-prune" }
    val frames = fixture.getValue("frames").jsonArray
    val source =
      if (dynamic) fixture.getValue("input").jsonArray.single().toString()
      else """{"ty":"sh","ks":${fixed(frames[0].jsonObject.getValue("source").toString())}}"""
    // Every vertex already has handles: rounding changes no geometry, but adds logical padding.
    val rounding = if (padded) """,{"ty":"rd","r":${fixed("1")}}""" else ""
    val offset = """{"ty":"op","a":${fixed("4")},"lj":1,"ml":${fixed("100")}}"""
    val stroke =
      """{"ty":"st","c":${fixed("[1,0,0,1]")},"o":${fixed("100")},"w":${fixed("2")},"lc":1,"lj":1,"ml":100}"""
    assertMatchesStaticFrames(
      animation("$source$rounding,$offset,$stroke"),
      referenceProbeAt = { Probe(32, 32, 1f, 1f) },
      artifactName =
        "offset-topology-split-prune${if (padded) "-padded" else ""}${if (dynamic) "" else "-static"}",
      frames = if (dynamic) (0..10).toList() + listOf(5, 0, 0) else listOf(0),
      maxMeanRedError = .0002f,
      maxPeakRedError = .3f,
      staticAt = { frame ->
        val path = frames[frame].jsonObject.getValue("expected")
        animation("""{"ty":"sh","ks":${fixed(path.toString())}},$stroke""")
      },
    )
  }

  private fun verify(name: String, static: Boolean = false, staticFrame: Int = 0) {
    val fixture =
      Json.parseToJsonElement(
          checkNotNull(javaClass.getResource("/offset-topology-reference.json")).readText()
        )
        .jsonObject
        .getValue("cases")
        .jsonArray
        .map { it.jsonObject }
        .single { it.getValue("name").jsonPrimitive.content == name }
    val shapes =
      fixture.getValue("input").jsonArray.joinToString(",") {
        if (static)
          JsonObject(
              it.jsonObject +
                ("pt" to Json.parseToJsonElement(fixed((3f + staticFrame * 0.4f).toString())))
            )
            .toString()
        else it.toString()
      }
    val offset = """{"ty":"op","a":${fixed("2")},"lj":1,"ml":${fixed("100")}}"""
    val stroke =
      """{"ty":"st","c":${fixed("[1,0,0,1]")},"o":${fixed("100")},"w":${fixed("2")},"lc":1,"lj":1,"ml":100}"""
    assertMatchesStaticFrames(
      animation("$shapes,$offset,$stroke"),
      referenceProbeAt = { Probe(32, 32, 1f, 1f) },
      artifactName =
        "offset-topology-$name${if (static) "-static${if (staticFrame == 0) "" else "-$staticFrame"}" else ""}",
      frames = if (static) listOf(staticFrame) else (0..10).toList() + listOf(5, 0, 0),
      maxMeanRedError = 0.0002f,
      maxPeakRedError = 0.3f,
      staticAt = { frame ->
        val path = fixture.getValue("frames").jsonArray[frame].jsonObject.getValue("expected")
        animation("""{"ty":"sh","ks":${fixed(path.toString())}},$stroke""")
      },
    )
  }
